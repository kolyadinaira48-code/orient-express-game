def finale(ask, say, journal):
    """Финальный выбор подозреваемого. Только ask/say, без input/print."""
    try:
        say("\nРАССЛЕДОВАНИЕ ЗАВЕРШЕНО. ПОРА НАЗВАТЬ ПОДОЗРЕВАЕМОГО.")
        suspects = [p for p in PASSENGERS if p.status != "жертва"]

        while True:
            say("\nКто убил Адриана Рида? Введите номер: ")
            for i, person in enumerate(suspects, 1):
                say(f"{i}. {person.name_ru}")
            say("0. Показать журнал улик")

            raw = ask(" > ")

            try:
                choice = int(raw)
            except ValueError:
                say("Пожалуйста, введите число из списка.")
                continue

            if choice == 0:
                say("\nЖУРНАЛ РАССЛЕДОВАНИЯ:")
                for clue in journal:
                    say(clue)
                continue

            if 1 <= choice <= len(suspects):
                if suspects[choice - 1].status == "убийца":
                    say(FINAL_REVEAL)
                    return
                # Игрок ошибся — выводим сообщение и ждём нажатия Enter
                say(NOT_CONFIRMED)
                ask("")  # пауза до нажатия Enter
            else:
                say("Такого варианта нет. Попробуйте снова.")

    except (EOFError, KeyboardInterrupt):
        return

