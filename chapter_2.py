# ---------- Раунд 3. Таинственная телеграмма ----------

TELEGRAM_TEXT = """ВОСТОЧНЫЙ ЭКСПРЕСС
ЛИЧНАЯ ТЕЛЕГРАММА

Дата отправления: 18 ноября 1934 года
Время отправления: 20:05
Время получения: 20:40

Получатель: Джулиан Мерсер

Содержание:
Синяя книга не должна попасть в Париж.

Заберите конверт, связанный с сообщением MSG-JM-421, до 22:30.
Рид не должен разговаривать с инспектором.
Документ MSG-AR-104 является отвлекающим материалом.
При необходимости используйте сведения из сообщения MSG-CL-208.

Также упоминается код MSG-XYZ-999, но он недействителен.

Отправитель неизвестен."""

EXPECTED_MSG = ["MSG-JM-421", "MSG-AR-104", "MSG-CL-208"]

class TelegramRound(Round):
    def __init__(self, *args, **kwargs):
        super().__init__(*args, **kwargs)

    def evaluate(self, compiled):
        got = [m.group(0) for m in compiled.finditer(TELEGRAM_TEXT)]
        if got == EXPECTED_MSG:
            return True, "Задание выполнено!"
        
        # Проверяем, не найдены ли лишние коды
        if len(got) > len(EXPECTED_MSG):
            extra = [code for code in got if code not in EXPECTED_MSG]
            if extra:
                return False, f"Найден лишний код: {extra[0]}. Должны быть только коды с двумя буквами."
        
        if got:
            sample = got[0]
            if not sample.startswith("MSG"):
                return False, "Идентификатор сообщения должен начинаться с MSG — три заглавные английские буквы."
            parts = sample.split("-")
            if len(parts) >= 2 and not re.fullmatch(r"[A-Z]{2}", parts[1]):
                return False, "После первого дефиса должны находиться ровно две заглавные английские буквы."
            if len(parts) >= 3 and not re.fullmatch(r"[0-9]{3}", parts[2]):
                return False, "В конце идентификатора должны находиться ровно три цифры от 0 до 9."
        
        return False, f"Список сообщений распознан неверно.\nОжидалось: {fmt_list(EXPECTED_MSG)}\nНайдено: {fmt_list(got)}"

