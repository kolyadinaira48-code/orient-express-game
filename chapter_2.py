# ---------- Раунд 4. Секретный отчёт ----------
REPORT_TEXT = """СЛУЖЕБНЫЙ ОТЧЁТ

СВИДЕТЕЛЬ: Анри Дюбуа
В 22:05 я видел Адриана Рида. Он возвращался в своё купе № 7.

СВИДЕТЕЛЬ: Томас Хейл
В 22:18 я заметил Джулиана Мерсера возле служебного коридора.

СВИДЕТЕЛЬ: Елена Соколова
Около 22:25 я услышала громкий спор возле купе № 7.

СВИДЕТЕЛЬ: Клара Лоран
Адриан Рид рассказывал мне о папке с финансовыми документами."""

EXPECTED_REPORT = """СЛУЖЕБНЫЙ ОТЧЁТ

СВИДЕТЕЛЬ: [СКРЫТО]
В 22:05 я видел Адриана Рида. Он возвращался в своё купе № 7.

СВИДЕТЕЛЬ: [СКРЫТО]
В 22:18 я заметил Джулиана Мерсера возле служебного коридора.

СВИДЕТЕЛЬ: [СКРЫТО]
Около 22:25 я услышала громкий спор возле купе № 7.

СВИДЕТЕЛЬ: [СКРЫТО]
Адриан Рид рассказывал мне о папке с финансовыми документами."""

class ReportRound(Round):
    def __init__(self, *args, **kwargs):
        super().__init__(*args, **kwargs)

    def evaluate(self, compiled):
        # Используем lambda, чтобы избежать проблем с экранированием \1, как рекомендовано в инструкции
        got = compiled.sub(lambda m: "[СКРЫТО]", REPORT_TEXT)

        if got == EXPECTED_REPORT:
            return True, "Задание выполнено!"

        # Анализ ошибок согласно документу "Обработка ошибок"
        if "СВИДЕТЕЛЬ: [СКРЫТО]" not in got:
            if "СВИДЕТЕЛЬ:" not in got:
                return False, "Метка СВИДЕТЕЛЬ: написана заглавными русскими буквами и должна остаться после замены имени."
            return False, "Имя должно состоять из русских букв: первая заглавная, остальные строчные."

        # Проверка на лишние изменения
        expected_lines = EXPECTED_REPORT.splitlines()
        got_lines = got.splitlines()
        for i, (e, g) in enumerate(zip(expected_lines, got_lines)):
            if e != g:
                return False, f"Шаблон затрагивает лишний текст. Скрыть нужно только имя и фамилию.\nОшибка в строке {i + 1}:\n  ожидалось: {e}\n  получено:  {g}"

        return False, "Не все имена свидетелей заменены корректно."

